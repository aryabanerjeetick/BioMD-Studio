"""
Files API router — download simulation files and create ZIP exports.
"""

import os
import io
import zipfile
import json
from datetime import datetime, timezone
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse, StreamingResponse
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from ..database import get_db, SimulationJob, ProjectFile
from ..config import PROJECTS_DIR
from ..utils.file_utils import list_job_files, compute_checksum

router = APIRouter(prefix="/api/files", tags=["files"])


@router.get("/job/{job_id}")
async def list_files_for_job(job_id: str, db: AsyncSession = Depends(get_db)):
    """List all files generated by a simulation job."""
    result = await db.execute(select(SimulationJob).where(SimulationJob.id == job_id))
    job = result.scalar_one_or_none()
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")

    if not job.work_dir or not os.path.exists(job.work_dir):
        return {"files": [], "message": "No files found — job may not have started"}

    files = list_job_files(job.work_dir)

    # Categorize files
    categorized = []
    for f in files:
        ext = f["extension"]
        category = "other"
        description = ""

        if ext == ".gro":
            category = "structure"
            description = "GROMACS structure file"
        elif ext == ".pdb":
            category = "structure"
            description = "PDB structure file"
        elif ext == ".top":
            category = "topology"
            description = "GROMACS topology"
        elif ext == ".itp":
            category = "topology"
            description = "Include topology (position restraints, etc.)"
        elif ext == ".mdp":
            category = "parameters"
            description = "MD parameter file"
        elif ext == ".tpr":
            category = "input"
            description = "GROMACS portable run input"
        elif ext == ".xtc":
            category = "trajectory"
            description = "Compressed trajectory"
        elif ext == ".trr":
            category = "trajectory"
            description = "Full-precision trajectory"
        elif ext == ".edr":
            category = "energy"
            description = "Energy file"
        elif ext == ".log":
            category = "log"
            description = "GROMACS log"
        elif ext == ".cpt":
            category = "checkpoint"
            description = "Checkpoint for restart"
        elif ext == ".xvg":
            category = "data"
            description = "GROMACS data file"

        categorized.append({
            **f,
            "category": category,
            "description": description,
        })

    return {"job_id": job_id, "files": categorized}


@router.get("/download/{job_id}/{filename:path}")
async def download_file(job_id: str, filename: str,
                         db: AsyncSession = Depends(get_db)):
    """Download a specific file from a job."""
    result = await db.execute(select(SimulationJob).where(SimulationJob.id == job_id))
    job = result.scalar_one_or_none()
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")

    if not job.work_dir:
        raise HTTPException(status_code=404, detail="No work directory")

    filepath = os.path.join(job.work_dir, filename)

    # Security: prevent directory traversal
    real_work = os.path.realpath(job.work_dir)
    real_file = os.path.realpath(filepath)
    if not real_file.startswith(real_work):
        raise HTTPException(status_code=403, detail="Access denied")

    if not os.path.exists(filepath):
        raise HTTPException(status_code=404, detail="File not found")

    return FileResponse(filepath, filename=filename)


@router.get("/export-zip/{job_id}")
async def export_zip(job_id: str, db: AsyncSession = Depends(get_db)):
    """
    Export all job files as a ZIP archive with a manifest.
    """
    result = await db.execute(select(SimulationJob).where(SimulationJob.id == job_id))
    job = result.scalar_one_or_none()
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")

    if not job.work_dir or not os.path.exists(job.work_dir):
        raise HTTPException(status_code=404, detail="No files to export")

    files = list_job_files(job.work_dir)

    # Create ZIP in memory
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as zf:
        manifest = {
            "job_id": job_id,
            "project_id": job.project_id,
            "created_at": job.created_at.isoformat() if job.created_at else None,
            "status": job.status,
            "force_field": job.force_field,
            "water_model": job.water_model,
            "gromacs_version": job.gromacs_version,
            "n_total_atoms": job.n_total_atoms,
            "exported_at": datetime.now(timezone.utc).isoformat(),
            "files": [],
        }

        for f in files:
            # Skip huge trajectory files from ZIP (user can download separately)
            if f["size_bytes"] > 500 * 1024 * 1024:  # 500MB limit
                manifest["files"].append({
                    "filename": f["relative_path"],
                    "size_bytes": f["size_bytes"],
                    "included": False,
                    "reason": "File exceeds 500MB — download separately",
                })
                continue

            zf.write(f["absolute_path"], f["relative_path"])
            manifest["files"].append({
                "filename": f["relative_path"],
                "size_bytes": f["size_bytes"],
                "included": True,
            })

        # Add manifest
        zf.writestr("MANIFEST.json", json.dumps(manifest, indent=2))

    buffer.seek(0)
    return StreamingResponse(
        buffer,
        media_type="application/zip",
        headers={
            "Content-Disposition": f"attachment; filename=md_simulation_{job_id[:8]}.zip"
        },
    )


